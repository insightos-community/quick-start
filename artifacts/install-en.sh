def download(url, target, limit):
    status('[>] Downloading release archive' if limit > 1024*1024 else '[>] Reading release manifest')
    scheme = urllib.parse.urlsplit(url).scheme
    if scheme != 'https' and not (a.allow_http and scheme == 'http'):
        raise ValueError('Downloads require HTTPS; use --allow-http explicitly for local testing')
    class Redirect(urllib.request.HTTPRedirectHandler):
        def redirect_request(self, req, fp, code, msg, headers, newurl):
            if urllib.parse.urlsplit(newurl).scheme != 'https' and not a.allow_http:
                raise ValueError('HTTPS downgrade redirect refused')
            return super().redirect_request(req, fp, code, msg, headers, newurl)
    try:
        response = urllib.request.build_opener(Redirect()).open(url, timeout=60)
    except Exception as error:
        raise RuntimeError('Download failed (HTTP '+str(getattr(error, 'code', 'unknown'))+
            '); check connectivity to the selected download host and any explicitly supplied ticket.') from None
    with response, target.open('wb') as f:
        size = 0
        total = int(response.headers.get('Content-Length', '0'))
        last = 0
        while block := response.read(1024 * 1024):
            size += len(block)
            if size > limit: raise ValueError('Download exceeds the size limit')
            f.write(block)
            if limit > 1024*1024 and time.monotonic() - last >= .2:
                byte_progress(size, total)
                last = time.monotonic()
        if total and total != size:
            raise ValueError('Downloaded size does not match Content-Length')
        if limit > 1024*1024:
            byte_progress(size, total, final=True)
def digest(path):
    h = hashlib.sha256()
    with path.open('rb') as f:
        while block := f.read(1024 * 1024): h.update(block)
    return h.hexdigest()
