            '            break\n'
            '    busy = []\n'
            "    prefix = str(root)+'/'\n"
            "    for proc in Path('/proc').iterdir():\n"
            '        if not proc.name.isdigit() or int(proc.name) == os.getpid() or int(proc.name) in allowed:\n'
            '            continue\n'
            '        pid = int(proc.name)\n'
            '        try:\n'
            "            args = (proc/'cmdline').read_bytes().decode(errors='replace').split('\\0')\n"
            '            reasons = []\n'
            "            if pid not in ignored and any(arg == str(root) or arg.startswith(prefix) or ('='+prefix) in arg for arg in args):\n"
            "                reasons.append('Command arguments reference this instance')\n"
            '            if proc.stat().st_uid == os.geteuid():\n'
            "                for name in ('exe', 'cwd'):\n"
            '                    try:\n'
            '                        target = os.readlink(proc/name)\n'
            "                        # Linux retains an unlinked directory as a shell's cwd.\n"
            '                        # Its textual path ends in " (deleted)", but it no longer\n'
            '                        # references the live installation tree. Check the inode,\n'
            '                        # not that suffix: a real directory may have that name.\n'
            "                        if name == 'cwd' and (proc/name).stat().st_nlink == 0:\n"
            '                            continue\n'
            '                        if target == str(root) or target.startswith(prefix):\n'
            "                            reasons.append(('Working directory: ' if name == 'cwd' else 'Executable: ') + target)\n"
            '                    except (FileNotFoundError, PermissionError):\n'
            '                        # Protected system services may expose cmdline but not exe/cwd.\n'
            '                        # Their readable command arguments are still checked above.\n'
            '                        pass\n'
            '            if reasons and uninstall_identity(pid) is not None:\n'
            "                command = (proc/'comm').read_text().strip()\n"
            "                busy.append({'pid': pid, 'command': ''.join(c for c in command if c.isprintable()),\n"
            "                             'reasons': reasons})\n"
            '        except (FileNotFoundError, ProcessLookupError):\n'
            '            continue\n'
            '        except PermissionError:\n'
            '            # Same-user processes must be inspectable; do not silently assume safety.\n'
            '            if proc.exists() and proc.stat().st_uid == os.geteuid():\n'
            "                raise RuntimeError(f'Cannot inspect same-user process {pid}; uninstall refused')\n"
            "    return sorted(busy, key=lambda item: item['pid'])\n"
            '\n'
            '\n'
            'def uninstall_busy(root, allowed):\n'
            '    busy = uninstall_processes(root, allowed)\n'
            '    if busy:\n'
            '        details = \'; \'.join(f"PID {item[\'pid\']} ({item[\'command\']}): " + \', \'.join(item[\'reasons\']) for item in busy)\n'
            "        raise RuntimeError('Active processes still reference this instance; no files deleted. '+details+\n"
            "                           '. For a terminal working directory, run cd ~ in that terminal or close it. Stop services using their own controls. Unrelated processes are never killed automatically.')\n"
            '\n'
            '\n'
            'def uninstall_confirm(root, purge, yes):\n'
            '    if yes:\n'
            '        return\n'
            '    try:\n'
            "        with open('/dev/tty', 'w', encoding='utf-8') as output, open('/dev/tty', 'r', encoding='utf-8') as source:\n"
            "            output.write(f'Uninstall {root}'+(' and permanently delete ALL configuration, data and logs?' if purge else ' (keep configuration, data and logs)?')+' [y/N] ')\n"
            '            output.flush()\n'
            '            answer = source.readline().strip().lower()\n'
            '    except OSError:\n'
            "        raise RuntimeError('Non-interactive mode requires --yes; review the plan with --dry-run first')\n"
            "    if answer not in ('y', 'yes'):\n"
            "        raise RuntimeError('Uninstall cancelled by user')\n"
            '\n'
            '\n'
            'def uninstall_shortcuts(root, state, note, dry_run=False):\n'
            '    identity = hashlib.sha256(str(root).encode()).hexdigest()[:12]\n'
            '    home = Path.home().resolve()\n'
            "    for name, checksum in state.get('desktop_shortcuts', {}).items():\n"
            '        path = Path(name)\n'
            "        if (not path.is_absolute() or home not in path.parents or path.name != f'semantic-{identity}.desktop'\n"
            '                or any(p.is_symlink() for p in [path, *path.parents]) or not path.is_file()):\n'
            '            continue\n'
            '        if path.stat().st_uid != os.geteuid() or path.stat().st_nlink != 1 or hashlib.sha256(path.read_bytes()).hexdigest() != checksum:\n'
            "            note('preserved modified shortcut '+str(path))\n"
            '            continue\n'
            "        note(('would remove ' if dry_run else 'removed ') + str(path))\n"
            '        if not dry_run:\n'
            '            path.unlink()\n'
            '\n'
            '\n'
            'def uninstall_entry(argv):\n'
            "    parser = argparse.ArgumentParser(description='Semantic safe offline uninstall; no artifact downloads or removal of shared system dependencies')\n"
            "    parser.add_argument('--dir', default=str(Path.home()/'.local/share/semantic'))\n"
            "    parser.add_argument('--purge', action='store_true', help='Permanently delete all configuration, databases, logs and other files in this instance')\n"
            "    parser.add_argument('--yes', action='store_true')\n"
            "    parser.add_argument('--dry-run', action='store_true', help='Inspect and show the plan without stopping processes or deleting files')\n"
            '    a = parser.parse_args(argv)\n'
            "    fd, logfile = tempfile.mkstemp(prefix='semantic-uninstall-', suffix='.log')\n"
            '    os.close(fd)  # 0600; outside the instance so purge cannot erase failure evidence.\n'
            "    print('Uninstall log:', logfile, flush=True)\n"
            '    def note(message):\n'
            "        with open(logfile, 'a') as f:\n"
            "            f.write(message+'\\n')\n"
            '    try:\n'
            '        root, state = uninstall_root(a.dir)\n'
            "        note(f'root={root}; purge={a.purge}; dry_run={a.dry_run}')\n"
            '        owned = uninstall_managed(root)\n'
            '        uninstall_busy(root, owned)\n'
            "        targets = [root] if a.purge else [root/name for name in (*UNINSTALL_DIRS, 'current')\n"
            '                                          if (root/name).exists() or (root/name).is_symlink()]\n'
            "        print('Verified Server/Web PIDs to stop:', ', '.join(map(str, owned)) or 'None')\n"
            '        for path in targets:\n'
            "            print('Will remove:', path)\n"
            '        if not a.purge:\n'
            "            print('Keeping configuration, databases, logs, scene/Robot data and other non-program directories. Reinstall the same version to restore the runtime.')\n"
            '        if a.dry_run:\n'
            '            uninstall_shortcuts(root, state, note, dry_run=True)\n'
            "            note('dry-run complete; no processes stopped or files deleted')\n"
            '            return\n'
            '        uninstall_confirm(root, a.purge, a.yes)\n'
            "        (root/'run').mkdir(exist_ok=True, mode=0o700)\n"
            "        lockfd = os.open(root/'run/install.lock', os.O_RDWR | os.O_CREAT | os.O_NOFOLLOW, 0o600)\n"
            "        with os.fdopen(lockfd, 'r+') as lock:\n"
            '            fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)\n'
            '            uninstall_root(str(root))  # Validate again after confirmation and locking.\n'
            '            owned = uninstall_managed(root)\n'
            '            uninstall_busy(root, owned)\n'
            '            for pid, ticks in owned.items():\n'
            '                if uninstall_identity(pid) == ticks:\n'
            '                    os.kill(pid, signal.SIGTERM)  # Never signal arbitrary process groups/Robots.\n'
            "                    note(f'SIGTERM owned PID {pid}')\n"
            '            deadline = time.monotonic()+20\n'
            '            while any(uninstall_identity(pid) == ticks for pid, ticks in owned.items()):\n'
            '                if time.monotonic() >= deadline:\n'
            "                    raise RuntimeError('Server/Web did not stop within 20 seconds; no data deleted and no processes forcibly killed')\n"
            '                time.sleep(.1)\n'
            '            uninstall_busy(root, {})\n'
            '            uninstall_shortcuts(root, state, note)\n'
            '            if a.purge:\n'
            '                shutil.rmtree(root)\n'
            "                note('purge complete; entire managed instance removed')\n"
            '            else:\n'
            '                # Persist a non-runnable state before removing binaries; failed deletion is retryable.\n'
            "                state.update(ready=False, uninstalled_at=time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()))\n"
            "                for path, value in ((root/'install.json', state), (root/'run/services.json', {})):\n"
            "                    descriptor, temporary = tempfile.mkstemp(prefix='.uninstall-state-', dir=path.parent)\n"
            "                    with os.fdopen(descriptor, 'w') as f:\n"
            '                        json.dump(value, f, indent=2)\n'
            '                    os.replace(temporary, path)\n'
            '                for path in targets:\n'
            '                    if path.is_symlink():\n'
            '                        path.unlink()\n'
            '                    elif path.is_dir():\n'
            '                        shutil.rmtree(path)\n'
            "                    note('removed '+str(path))\n"
            "                note('uninstall complete; user data preserved')\n"
            "        print('Uninstall complete. '+('The entire instance has been permanently deleted; this script cannot restore it.' if a.purge else 'Programs removed; configuration, data and logs preserved.'))\n"
            "        print('System packages were not removed. Only unchanged shortcuts created by this instance were removed. Log:', logfile)\n"
            '    except Exception:\n'
            "        with open(logfile, 'a') as f:\n"
